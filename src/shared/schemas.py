# External imports -----------------------------------------------------------------------------------------------------
from pydantic import BaseModel

# বাংলা ব্যাখ্যা: এটি 'pydantic' লাইব্রেরি থেকে 'BaseModel' ক্লাসটি ইমপোর্ট করে, যা অ্যাপ্লিকেশনের ভেতরে ডেটা ভ্যালিডেশন স্কিমা এবং স্ট্রাকচার ডিফাইন
# করার মূল ভিত্তি হিসেবে কাজ করে।





# Shared schemas -------------------------------------------------------------------------------------------------------

# Simple confirmation response used by several features (logout, delete transaction, ...)
class MessageResponse(BaseModel):
    message: str

# বাংলা ব্যাখ্যা: এটি 'BaseModel' থেকে ইনহেরিট করা 'MessageResponse' নামের একটি শেয়ারড পাইডান্টিক মডেল ডিফাইন করে যা আউটপুটের সুনির্দিষ্ট গঠন
# নিশ্চিত করে। এর ভেতরে 'str' টাইপের একটিমাত্র 'message' ফিল্ড রাখা হয়েছে, যা ক্লায়েন্টকে পরিষ্কার স্ট্যাটাস কনফারমেশন টেক্সট পাঠানোর জন্য লগআউট বা
# ট্রানজ্যাকশন ডিলিশনের মতো বিভিন্ন ফিচার জুড়ে ব্যবহার করা হয়।





