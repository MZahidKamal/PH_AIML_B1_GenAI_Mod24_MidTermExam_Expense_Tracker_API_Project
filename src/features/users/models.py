# External imports -----------------------------------------------------------------------------------------------------
from sqlalchemy import String
from sqlalchemy.orm import Mapped, mapped_column, relationship
from typing import TYPE_CHECKING

# Internal imports -----------------------------------------------------------------------------------------------------
from src.db.base import SqlalchemyBase
from src.features.users.constants import USERNAME_MAX_LENGTH, EMAIL_MAX_LENGTH, HASHED_PASSWORD_MAX_LENGTH

# Imported only for type checkers (avoids a circular import at runtime)
if TYPE_CHECKING:
    from src.features.auth.models import RefreshToken
    from src.features.transactions.models import Transaction




# Database model -------------------------------------------------------------------------------------------------------

# Define the 'users' table
class User(SqlalchemyBase):
    __tablename__ = "users"

    # Primary key, auto-generated by PostgreSQL
    id: Mapped[int] = mapped_column(primary_key=True)

    # Unique username; index=True speeds up lookups during login
    username: Mapped[str] = mapped_column(String(USERNAME_MAX_LENGTH), unique=True, index=True)

    # Unique email address (always stored in lowercase, normalized by the schema)
    email: Mapped[str] = mapped_column(String(EMAIL_MAX_LENGTH), unique=True, index=True)

    # Argon2 hash of the password; the raw password is never stored
    hashed_password: Mapped[str] = mapped_column(String(HASHED_PASSWORD_MAX_LENGTH))

    # One-to-many: all refresh tokens of this user; passive_deletes lets the database's ON DELETE CASCADE do the work
    refresh_tokens: Mapped[list["RefreshToken"]] = relationship(back_populates="user", passive_deletes=True)

    # One-to-many: all transactions owned by this user
    transactions: Mapped[list["Transaction"]] = relationship(back_populates="owner", passive_deletes=True)

    # Readable representation for debugging (never includes the password hash)
    def __repr__(self) -> str:
        return f"<User id={self.id} username={self.username!r}>"





